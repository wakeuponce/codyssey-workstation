#!/usr/bin/env bash
# =============================================================================
# 실행 로그를 마크다운(.md)으로 감싸 저장하는 헬퍼.
#
#   표준입력으로 들어온 스크립트 출력을 코드펜스로 감싸 logs/*.md 로 떨군다.
#   출력 자체는 한 글자도 편집하지 않는다. 감싸기만 한다.
#
# 사용:
#   bash scripts/01-terminal-basics.sh 2>&1 \
#     | bash scripts/_capture.sh logs/01-terminal.md "01. 터미널 기본 조작"
# =============================================================================
set -uo pipefail

OUT="${1:?사용법: _capture.sh <출력파일.md> <제목>}"
TITLE="${2:?사용법: _capture.sh <출력파일.md> <제목>}"

{
  printf '# %s — 실행 로그\n\n' "$TITLE"
  printf '> 스크립트의 **실제 출력 전문**입니다. 아래 코드펜스 안의 내용은 편집하지 않았습니다.\n'
  printf '> `$` 로 시작하는 줄이 입력한 명령, 그 아래가 그 명령의 출력입니다.\n\n'
  printf '```console\n'
  cat
  printf '```\n'
} > "$OUT"

printf '기록됨: %s (%s 줄)\n' "$OUT" "$(wc -l < "$OUT")" >&2
