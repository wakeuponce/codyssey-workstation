#!/usr/bin/env bash
# 공통 헬퍼: 실행한 "명령어"와 "출력 결과"를 함께 남기기 위한 래퍼.
# 미션의 증거 수집 규칙("명령어 입력과 출력 결과가 함께 포함") 을 만족시키는 것이 목적이다.

# 명령을 화면에 먼저 찍고 실행한다.
run() {
  printf '\n$ %s\n' "$*"
  eval "$@" 2>&1 || printf '[exit=%s]\n' "$?"
}

# 단락 제목
section() {
  printf '\n\n########## %s ##########\n' "$*"
}

# 설명 주석 (로그 안에서 왜 이 명령을 쳤는지 남긴다)
note() {
  printf '\n# %s\n' "$*"
}
